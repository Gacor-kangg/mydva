/// Mengurutkan dari rilis terbaru ke terlama (tidak mengubah list aslinya).
List<MediaModel> sortedByNewest(List<MediaModel> list) {
  final result = List<MediaModel>.from(list);
  result.sort((a, b) => (b.releaseYear ?? 0).compareTo(a.releaseYear ?? 0));
  return result;
}

